# Builds THIRD_PARTY_NOTICES.txt for the installer (ADR-057). Dot-sourced by
# build-installer.ps1; licence texts are read from the staged packages, vcpkg's share
# folder and packaging/licenses (texts no installed package carries).

function Write-Notices {
    param(
        [Parameter(Mandatory)] [string]$Path,
        [Parameter(Mandatory)] [string]$Repo,
        [Parameter(Mandatory)] [string]$VcpkgShare,
        [Parameter(Mandatory)] [string]$PyDir,
        [Parameter(Mandatory)] [string]$SitePackages,
        [Parameter(Mandatory)] [string]$CrtDir,
        [Parameter(Mandatory)] [string]$PythonVersion
    )
    $licenses = Join-Path $Repo 'packaging\licenses'
    $sb = New-Object System.Text.StringBuilder
    $rule = '=' * 78

    function Add([string]$text) { [void]$sb.AppendLine($text) }
    function Add-Section([string]$title, [string]$body) {
        Add ''; Add $rule; Add $title; Add $rule; Add ''
        if ($body) { Add $body.TrimEnd() }
    }
    function Add-File([string]$file) {
        Add ''
        Add ((Get-Content -Raw -LiteralPath $file).TrimEnd())
    }

    Add 'QUADmapper - third-party notices'
    Add ''
    Add 'QUADmapper includes the third-party software listed below. Each part keeps its own'
    Add 'licence, reproduced here. Part A ships with every install; Part B only with the'
    Add 'optional "AI features" component (installed under ai\).'

    # ------------------------------------------------------------------ Part A
    Add ''; Add ''; Add 'PART A - QUADMAPPER APPLICATION'

    $ffmpegVersion = '7.1.2'
    $info = Get-ChildItem -LiteralPath (Join-Path $VcpkgShare '..\..\vcpkg\info') -Filter 'ffmpeg_*_x64-windows.list' -ErrorAction SilentlyContinue |
        Select-Object -First 1
    if ($info -and $info.Name -match '^ffmpeg_([^_]+)_') { $ffmpegVersion = $Matches[1] }
    Add-Section "FFmpeg $ffmpegVersion (libavcodec, libavformat, libavutil, libavdevice, libavfilter, libswscale, libswresample)" @"
Licence: GNU Lesser General Public License, version 2.1 or later (LGPL-2.1-or-later).
This build was configured without --enable-gpl and without --enable-nonfree (built by
vcpkg; the DLLs report "LGPL version 2.1 or later"). QUADmapper links to FFmpeg
dynamically: the av*.dll and sw*.dll files in the install folder may be replaced with
compatible builds of your own. The FFmpeg source code for this version is available at
https://ffmpeg.org/releases/ffmpeg-$ffmpegVersion.tar.xz and https://github.com/FFmpeg/FFmpeg .
"@
    Add-File (Join-Path $VcpkgShare 'ffmpeg\copyright')

    foreach ($pkg in @(
            @{ Dir = 'glfw3'; Title = 'GLFW (zlib/libpng licence)' },
            @{ Dir = 'glm'; Title = 'GLM - OpenGL Mathematics (Happy Bunny / MIT licence)' },
            @{ Dir = 'nlohmann-json'; Title = 'JSON for Modern C++ by Niels Lohmann (MIT licence)' },
            @{ Dir = 'miniaudio'; Title = 'miniaudio (public domain or MIT No Attribution)' })) {
        Add-Section $pkg.Title ''
        Add-File (Join-Path $VcpkgShare "$($pkg.Dir)\copyright")
    }

    Add-Section 'Dear ImGui (MIT licence)' ''
    Add-File (Join-Path $licenses 'imgui-LICENSE.txt')
    Add-Section 'stb_image and stb_dxt by Sean Barrett (MIT or public domain)' ''
    Add-File (Join-Path $licenses 'stb-LICENSE.txt')

    $khr = Get-Content -Raw -LiteralPath (Join-Path $Repo 'external\glad\include\KHR\khrplatform.h')
    $khrComment = [regex]::Match($khr, '/\*[\s\S]*?\*/').Value
    Add-Section 'glad 0.1.36 OpenGL loader (generated code) and Khronos khrplatform.h' @"
The OpenGL loader was generated by glad (https://github.com/Dav1dde/glad, MIT licence)
from the Khronos OpenGL API registry (Apache License 2.0; see Part B for the full text).
khrplatform.h carries its own notice:

$khrComment
"@

    Add-Section 'Notices from the QUADmapper source tree (Snappy, HAP, stb_dxt, fonts)' ''
    Add-File (Join-Path $Repo 'THIRD-PARTY-NOTICES.md')
    Add-Section 'Hanken Grotesk - SIL Open Font License 1.1' ''
    Add-File (Join-Path $licenses 'OFL-1.1-HankenGrotesk.txt')
    Add-Section 'JetBrains Mono - SIL Open Font License 1.1' ''
    Add-File (Join-Path $licenses 'OFL-1.1-JetBrainsMono.txt')

    $crtFiles = (Get-ChildItem -LiteralPath $CrtDir -Filter *.dll).Name -join ', '
    Add-Section 'Microsoft Visual C++ Runtime' @"
$crtFiles
Redistributable code of Microsoft Visual Studio 2022, distributed under the Visual Studio
licence terms (https://visualstudio.microsoft.com/license-terms/). Copyright (c) Microsoft
Corporation. Also installed beside the bundled Python in Part B.
"@

    Add-Section 'GoogleTest (BSD-3-Clause)' @"
Used to build and run QUADmapper's tests only. It is not part of this installer.
"@

    # ------------------------------------------------------------------ Part B
    Add ''; Add ''; Add 'PART B - AI FEATURES (optional component, installed under ai\)'

    Add-Section "Python $PythonVersion (embeddable package from python.org) - PSF License" ''
    Add-File (Join-Path $PyDir 'LICENSE.txt')

    $torchLib = Join-Path $SitePackages 'torch\lib'
    $nvidia = Get-ChildItem -LiteralPath $torchLib -Filter *.dll |
        Where-Object { $_.Name -match '^(cu|nv|caffe2_nvrtc)' } | ForEach-Object { $_.Name }
    Add-Section 'NVIDIA CUDA runtime and cuDNN (redistributable files, bundled in the PyTorch wheel)' @"
$($nvidia -join ', ')

These files are NVIDIA redistributable components, distributed unmodified inside the
official PyTorch CUDA 12.6 wheel under the NVIDIA CUDA Toolkit End User License
Agreement (https://docs.nvidia.com/cuda/eula/index.html, Attachment A lists the
redistributable files) and the NVIDIA cuDNN Software License Agreement
(https://docs.nvidia.com/deeplearning/cudnn/latest/reference/eula.html).
Copyright (c) NVIDIA Corporation. All rights reserved.
They are used only when an NVIDIA GPU is present; otherwise the AI features run on the CPU.
"@
    if (Test-Path -LiteralPath (Join-Path $torchLib 'libiomp5md.dll')) {
        Add-Section 'Intel OpenMP runtime (libiomp5md.dll, bundled in the PyTorch wheel)' @"
Redistributed unmodified as part of the PyTorch wheel. Copyright (c) Intel Corporation.
See the PyTorch licence below for the terms that cover the files PyTorch redistributes.
"@
    }

    Add-Section 'SAM 2.1 model checkpoints (sam2.1_hiera_small.pt, sam2.1_hiera_tiny.pt)' @"
Segment Anything Model 2 by Meta Platforms, Inc. (https://github.com/facebookresearch/sam2).
Licence: Apache License 2.0, the same as the sam2 package listed below.
"@
    Add-Section 'Depth Anything V2 Small model (depth-anything-v2-small)' @"
Depth Anything V2 Small by the Depth Anything authors
(https://huggingface.co/depth-anything/Depth-Anything-V2-Small-hf).
Licence: Apache License 2.0 (the full text is with the transformers package below).
Only the Small model is included; the larger variants are under a non-commercial licence
and are not part of QUADmapper.
"@

    # Every installed Python distribution, with its metadata licence and licence files.
    $dists = Get-ChildItem -LiteralPath $SitePackages -Directory -Filter '*.dist-info' | Sort-Object Name
    foreach ($dist in $dists) {
        $meta = Join-Path $dist.FullName 'METADATA'
        if (-not (Test-Path -LiteralPath $meta)) { continue }
        $name = ''; $version = ''; $lic = ''; $classifiers = @()
        foreach ($line in (Get-Content -LiteralPath $meta)) {
            if ($line -eq '') { break }  # headers end at the first blank line
            if ($line -match '^Name:\s*(.+)$') { $name = $Matches[1] }
            elseif ($line -match '^Version:\s*(.+)$') { $version = $Matches[1] }
            elseif ($line -match '^License-Expression:\s*(.+)$') { $lic = $Matches[1] }
            elseif ($line -match '^License:\s*(.+)$' -and -not $lic -and $Matches[1].Length -lt 120) { $lic = $Matches[1] }
            elseif ($line -match '^Classifier:\s*License ::\s*(.+)$') { $classifiers += $Matches[1] }
        }
        if (-not $lic -and $classifiers.Count -gt 0) { $lic = $classifiers -join '; ' }
        if (-not $lic) { $lic = 'see the licence text below' }
        Add-Section "$name $version (Python package) - $lic" ''
        $files = @(Get-ChildItem -LiteralPath $dist.FullName -File |
            Where-Object { $_.Name -match '^(LICEN[CS]E|COPYING|NOTICE|AUTHORS)' })
        $licDir = Join-Path $dist.FullName 'licenses'
        if (Test-Path -LiteralPath $licDir) { $files += @(Get-ChildItem -LiteralPath $licDir -File -Recurse) }
        if ($files.Count -eq 0) {
            Add "No licence file ships with this package; licence per its metadata: $lic."
        }
        foreach ($f in $files) {
            Add "--- $($f.Name) ---"
            Add-File $f.FullName
            Add ''
        }
    }

    [System.IO.File]::WriteAllText($Path, $sb.ToString().Replace("`r`n", "`n").Replace("`n", "`r`n"),
        (New-Object System.Text.UTF8Encoding($true)))
}
